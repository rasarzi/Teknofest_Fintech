import pandas as pd
import numpy as np
import json

def compute_features(input_file, output_file):
    print(f"Loading {input_file} for P18 Feature Engineering...")
    
    with open(input_file, 'r') as f:
        data = json.load(f)

    df = pd.DataFrame(data)
    df['date'] = pd.to_datetime(df['date'])
    df = df.sort_values(by=['ticker', 'date'])

    features_list = []

    # Calculate features independently for each stock/benchmark
    for ticker, group in df.groupby('ticker'):
        group = group.copy()
        
        # 1. Moving Averages
        group['sma_20'] = group['close'].rolling(window=20).mean()
        group['sma_50'] = group['close'].rolling(window=50).mean()
        
        # 2. Volatility (20-day rolling standard deviation)
        group['volatility_20d'] = group['close'].rolling(window=20).std()
        
        # 3. Momentum (Percentage change over 20 days)
        group['momentum_20d'] = group['close'].pct_change(periods=20)
        
        # 4. RSI (14-day Relative Strength Index)
        delta = group['close'].diff()
        gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
        loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
        rs = gain / loss
        group['rsi_14'] = 100 - (100 / (1 + rs))
        
        # 5. Drawdown (Drop from the highest peak so far)
        rolling_max = group['close'].cummax()
        group['drawdown'] = (group['close'] - rolling_max) / rolling_max

        # Clean up NaNs generated by rolling calculations
        group = group.bfill().ffill()
        
        # Format dates back to strings
        group['date'] = group['date'].dt.strftime('%Y-%m-%d')
        
        # Add to final list
        features_list.extend(group.to_dict(orient='records'))

    with open(output_file, 'w') as f:
        json.dump(features_list, f, indent=4)
        
    print(f"Task P18 Complete. Saved technical features to {output_file}")

if __name__ == "__main__":
    compute_features('structured_stock.json', 'stock_features.json')